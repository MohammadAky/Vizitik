<h4>۱) معرفی سامانه</h4>
<p>سامانه <strong>ویزیتیک</strong> یک سامانه‌ی ثبت سفارش، صدور فاکتور، بارگیری و مدیریت حساب مخصوص ویزیتورها و پخش‌کنندگان (توزیع مویرگی) است. با ثبت‌نام در این سامانه، شما به‌عنوان «ویزیتور» فعالیت می‌کنید و متعهد به رعایت مفاد این قوانین هستید.</p>

<h4>۲) صحت اطلاعات</h4>
<p>شما مسئول صحت اطلاعات واردشده (نام، شماره موبایل، رمز عبور و اطلاعات فروشگاه‌ها) هستید. ثبت اطلاعات نادرست یا استفاده از شماره‌ی متعلق به شخص دیگر بدون مجوز، مجاز نیست و مسئولیت عواقب آن بر عهده‌ی شماست.</p>

<h4>۳) امنیت حساب</h4>
<p>رمز عبور حساب شخصی شماست و نباید در اختیار دیگران قرار گیرد. تمام عملیاتی که با حساب شما (ثبت سفارش، صدور فاکتور، ویرایش و تسویه) انجام شود، به‌عنوان اقدام شما تلقی می‌گردد. در صورت مفقودی یا لو رفتن رمز، سریعاً آن را تغییر دهید.</p>

<h4>۴) دقت در ثبت سفارش و فاکتور</h4>
<p>مبالغ، تخفیف‌ها، روش تسویه و مشخصات اقلام باید قبل از ثبت نهایی دقیق بررسی شود. پس از صدور فاکتور، اطلاعات آن مبنای محاسبه‌ی موجودی خودرو و دفتر حساب مشتری قرار می‌گیرد.</p>

<h4>۵) حفظ حریم خصوصی</h4>
<p>اطلاعات فروشگاه‌ها و مشتریان (شماره تماس، مانده حساب و سوابق) محرمانه است و استفاده از آن‌ها صرفاً در چارچوب همین سامانه و برای جریان کسب‌وکار مجاز است. اشتراک‌گذاری این اطلاعات با اشخاص ثالث بدون مجوز ممنوع است.</p>

<h4>۶) استفاده از پیام‌رسان بله</h4>
<p>برای دریافت کدهای تایید، فاکتورها و اطلاع‌رسانی‌ها، شماره‌ی موبایل شما به ربات بله سامانه متصل می‌شود. با ثبت‌نام، رضایت خود را برای دریافت این پیام‌ها اعلام می‌کنید.</p>

<h4>۷) محدودیت مسئولیت</h4>
<p>ویزیتیک ابزاری برای مدیریت و مستندسازی فعالیت است. مسئولیت تحویل کالا، دریافت وجه و رعایت قوانین تجاری محل فعالیت (از جمله قیمت‌گذاری و فروش) بر عهده‌ی ویزیتور و کسب‌وکار مربوطه است و سامانه صرفاً عملیات را ثبت و محاسبه می‌کند.</p>

<h4>۸) اصلاح قوانین</h4>
<p>متن این قوانین ممکن است بر اساس نیاز سامانه به‌روزرسانی شود. ادامه‌ی استفاده از سامانه پس از هر تغییر، به‌منزله‌ی پذیرش نسخه‌ی جدید قوانین است.</p>
